/** Markdown report for one repository. */
import { gateCves, sevRank } from "./analyse.ts";
import { shortRef, versionOf } from "./refs.ts";
import type { Analysis, Cve, ScanMeta } from "./types.ts";

const CVES_PER_IMAGE = 20;
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ");
const ch = (c: { CRITICAL: number; HIGH: number }) => `${c.CRITICAL} / ${c.HIGH}`;

function cveLines(cves: Cve[], limit = CVES_PER_IMAGE): string[] {
  const sorted = [...cves].sort(
    (a, b) => sevRank(a.severity) - sevRank(b.severity) || Number(!a.fixed) - Number(!b.fixed) || a.id.localeCompare(b.id),
  );
  const lines = sorted.slice(0, limit).map((v) => {
    const pkg = `\`${v.pkgs[0]}\`${v.pkgs.length > 1 ? ` (+${v.pkgs.length - 1})` : ""}`;
    const fix = v.fixed ? ` → \`${v.fixed.slice(0, 40)}\`` : " (no fix yet)";
    const title = v.title ? ` — ${esc(v.title.slice(0, 90))}` : "";
    return `- **${v.severity.toLowerCase()}** ${v.url ? `[${v.id}](${v.url})` : v.id} ${pkg} \`${v.installed}\`${fix}${title}`;
  });
  if (sorted.length > limit) lines.push(`- … and ${sorted.length - limit} more`);
  return lines;
}

export interface SummaryOptions {
  reportUrl?: string;
  /** Link to the pull request of a Renovate branch, when the platform has a URL for it. */
  prUrl?: (branch: string) => string | undefined;
  maxRows?: number;
}

const plural = (n: number, word: string) => `${n} ${word}`;
const shortName = (name: string) => name.split("/").slice(-2).join("/");

/**
 * The section Renovate appends to its Dependency Dashboard, below its own
 * content. Short lists rather than tables, each fixing update linked to its
 * pull request. It is a Handlebars template, so braces are written as entities.
 */
export function renderSummary(a: Analysis, meta: ScanMeta, o: SummaryOptions = {}): string {
  const maxRows = o.maxRows ?? 10;
  const total = (k: "CRITICAL" | "HIGH") => a.images.reduce((n, i) => n + i.counts[k], 0);
  const exposed = a.images
    .filter((i) => i.counts.CRITICAL || i.counts.HIGH)
    .sort((x, y) => y.counts.CRITICAL - x.counts.CRITICAL || y.counts.HIGH - x.counts.HIGH || x.name.localeCompare(y.name));
  const fixing = a.updates.filter((u) => u.diff.fixedGate).sort((x, y) => y.diff.fixedGate - x.diff.fixedGate);
  const sev = (c: number, h: number) => [c ? plural(c, "critical") : "", h ? plural(h, "high") : ""].filter(Boolean).join(", ") || "none";
  const out = [
    "### 🛡️ Container image vulnerabilities",
    "",
    `Trivy found **${total("CRITICAL")} critical** and **${total("HIGH")} high** CVEs in ${a.images.length} images.` +
      (o.reportUrl ? ` [Full report](${o.reportUrl}).` : ""),
  ];
  if (fixing.length) {
    out.push("", `**${fixing.length === 1 ? "This update fixes" : "These updates fix"} some of them:**`, "");
    for (const u of fixing.slice(0, maxRows)) {
      const fixed = u.diff.fixed.filter((c) => c.severity === "CRITICAL" || c.severity === "HIGH");
      const what = `\`${shortName(u.fromName)}\` ${versionOf(u.from)} → ${versionOf(u.ref)}`;
      const url = u.branchName ? o.prUrl?.(u.branchName) : undefined;
      out.push(` - ${url ? `[${what}](${url})` : what}: fixes ${sev(fixed.filter((c) => c.severity === "CRITICAL").length, fixed.filter((c) => c.severity === "HIGH").length)}`);
    }
    if (fixing.length > maxRows) out.push(` - … and ${fixing.length - maxRows} more`);
  }
  const stuck = exposed.filter((i) => !fixing.some((u) => u.from === i.ref));
  if (stuck.length) {
    out.push("", `<details><summary>${stuck.length} more ${stuck.length === 1 ? "image has" : "images have"} critical/high CVEs and no update that fixes them</summary>`, "");
    for (const i of stuck.slice(0, maxRows)) out.push(` - \`${shortName(i.name)}\` ${versionOf(i.ref)}: ${sev(i.counts.CRITICAL, i.counts.HIGH)}${i.scan.eosl ? " (end-of-life OS)" : ""}`);
    if (stuck.length > maxRows) out.push(` - … and ${stuck.length - maxRows} more`);
    out.push("", "</details>");
  }
  if (a.errors.length) out.push("", `${a.errors.length} image references could not be scanned.`);
  out.push("", `<sub>[renovate-trivy](https://github.com/aslafy-z/renovate-trivy) · Trivy ${meta.trivyVersion} · scanned ${meta.scannedAt.slice(0, 16).replace("T", " ")} UTC</sub>`);
  return out.join("\n").replace(/[{}]/g, (c) => `&#${c.charCodeAt(0)};`);
}

export function renderReport(a: Analysis, meta: ScanMeta): string {
  const total = (k: "CRITICAL" | "HIGH") => a.images.reduce((n, i) => n + i.counts[k], 0);
  const exposed = a.images
    .filter((i) => i.counts.CRITICAL || i.counts.HIGH)
    .sort((x, y) => y.counts.CRITICAL - x.counts.CRITICAL || y.counts.HIGH - x.counts.HIGH || x.name.localeCompare(y.name));
  const fixing = a.updates.filter((u) => u.diff.fixedGate).sort((x, y) => y.diff.fixedGate - x.diff.fixedGate);
  const out = [
    `# Container image CVEs: ${a.repository}`,
    "",
    "Generated by [renovate-trivy](https://github.com/aslafy-z/renovate-trivy); overwritten on every run.",
    "",
    `**${a.images.length}** images scanned · **${total("CRITICAL")}** critical · **${total("HIGH")}** high · ` +
      `**${a.images.reduce((n, i) => n + i.fixableGate, 0)}** critical/high with an upstream fix · ` +
      `**${fixing.length}** Renovate updates fix some`,
    "",
    "## Renovate updates that fix critical/high CVEs",
    "",
  ];
  if (fixing.length) {
    out.push("| Image | Update | Critical / High | Fixed | New | Branch |", "|---|---|---|---|---|---|");
    for (const u of fixing) {
      out.push(
        `| \`${u.fromName}\` | \`${versionOf(u.from)}\` → \`${versionOf(u.ref)}\` | ${ch(u.fromCounts)} → ${ch(u.toCounts)} | ` +
          `${u.diff.fixedGate} | ${u.diff.introducedGate} | ${u.branchName ? `\`${u.branchName}\`` : ""} |`,
      );
    }
  } else out.push("None of the updates Renovate proposes today removes a critical or high CVE.");

  out.push("", "## Images with critical/high CVEs", "");
  if (exposed.length) {
    out.push("| Image | Version | Critical | High | Fixable | Best update | Used in |", "|---|---|---|---|---|---|---|");
    for (const i of exposed) {
      const best = a.updates.filter((u) => u.from === i.ref).sort((x, y) => y.diff.fixedGate - x.diff.fixedGate)[0];
      const upd = !best
        ? "—"
        : best.diff.fixedGate
          ? `\`${versionOf(best.ref)}\` (−${best.diff.fixedGate})`
          : `\`${versionOf(best.ref)}\` (fixes none)`;
      out.push(
        `| \`${i.name}\` | \`${versionOf(i.ref)}\`${i.scan.eosl ? " ⚠️ EOL OS" : ""} | ${i.counts.CRITICAL} | ${i.counts.HIGH} | ` +
          `${i.fixableGate} | ${upd} | ${i.files.map((f) => `\`${f}\``).join(", ")} |`,
      );
    }
    out.push("", "<details><summary>Critical/high CVEs per image</summary>", "");
    for (const i of exposed) {
      out.push(`#### \`${shortRef(i.ref)}\`${i.scan.os ? ` (${i.scan.os})` : ""}`, "", ...cveLines(gateCves(i.scan.vulns)), "");
    }
    out.push("</details>");
  } else out.push("No critical or high CVE in any scanned image.");

  if (a.errors.length || a.skipped.length) {
    out.push("", "## Not scanned", "");
    for (const e of a.errors) out.push(`- \`${e.ref}\`: ${esc(e.error)}`);
    for (const r of a.skipped) out.push(`- \`${r}\`: registry excluded from scanning`);
  }
  out.push(
    "",
    `<sub>Trivy ${meta.trivyVersion} · DB ${meta.dbUpdatedAt.slice(0, 16).replace("T", " ")} UTC · ${meta.platform} · ` +
      `scanned ${meta.scannedAt.slice(0, 16).replace("T", " ")} UTC</sub>`,
    "",
  );
  return out.join("\n");
}
